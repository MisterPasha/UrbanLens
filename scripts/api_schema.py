"""Export OpenAPI and deterministic TypeScript types directly from Pydantic contracts."""

from __future__ import annotations

import argparse
import json
from typing import Any

from scripts.dev import ROOT
from urbanlens.api.app import create_app


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    for key, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return "(" + separator.join(ts(s) for s in schema[key]) + ")"
    kind = schema.get("type")
    if isinstance(kind, list):
        return "(" + " | ".join(ts(dict(schema, type=k)) for k in kind) + ")"
    if kind == "array":
        return "(" + ts(schema.get("items", {})) + ")[]"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        required = schema.get("required", [])
        fields = [
            json.dumps(k) + ("" if k in required else "?") + ": " + ts(v)
            for k, v in properties.items()
        ]
        extra = schema.get("additionalProperties")
        if extra:
            fields.append("[key: string]: " + (ts(extra) if isinstance(extra, dict) else "unknown"))
        return "{ " + "; ".join(fields) + " }" if fields else "Record<string, unknown>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def export(*, check: bool = False) -> None:
    document = create_app().openapi()
    definitions = document.get("components", {}).get("schemas", {})
    types = [
        "// Generated by python scripts/dev.py api-schema. Edit Python contracts, then regenerate."
    ]
    types.extend(
        "export type " + name + " = " + ts(schema) + ";"
        for name, schema in sorted(definitions.items())
    )
    routes = []
    for path, operations in document["paths"].items():
        if "get" not in operations:
            continue
        op = operations["get"]
        parameters = {p["name"]: p["schema"] for p in op.get("parameters", [])}
        required = [p["name"] for p in op.get("parameters", []) if p.get("required")]
        response = op["responses"]["200"]["content"]["application/json"]["schema"]
        routes.append(
            json.dumps("GET " + path)
            + ": { params: "
            + ts(dict(type="object", properties=parameters, required=required))
            + "; response: "
            + ts(response)
            + " }"
        )
    types.append("export type ApiRoutes = {\n  " + ";\n  ".join(routes) + ";\n};")
    files = {
        ROOT / "reference/api/openapi.json": json.dumps(document, indent=2, sort_keys=True) + "\n",
        ROOT / "web/src/api/contracts.ts": "\n\n".join(types) + "\n",
    }
    for path, content in files.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise ValueError("API artifacts differ; run python scripts/dev.py api-schema")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print("OpenAPI and TypeScript contracts " + ("match" if check else "exported"))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    export(check=parser.parse_args().check)
