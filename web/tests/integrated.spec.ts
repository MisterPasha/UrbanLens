import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { areaCodes, firstRelease, secondRelease, journeyApi } from './fixtures/journey';
import type { JourneyControl } from './fixtures/journey';

test('anonymous desktop/mobile journey preserves filters and exposes accessible evidence, coverage, attribution and reuse', async ({ page }, testInfo) => {
  test.setTimeout(120_000);
  const requests: URL[] = [], reports: unknown[] = [];
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await journeyApi(page, { release: firstRelease, mode: 'ready' }, requests);
  async function audit(label: string) {
    const report = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
    reports.push({ label, violations: report.violations, incomplete: report.incomplete.map(item => ({ id: item.id, nodes: item.nodes.length })) });
    expect.soft(report.violations.map(item => ({ id: item.id, targets: item.nodes.map(node => node.target) })), `${label} accessibility`).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${label} width`).toBeTruthy();
  }
  await page.goto('/');
  await expect(page.locator('.venue-row')).toHaveCount(1);
  await page.keyboard.press('Tab'); await expect(page.getByRole('link', { name: 'Skip to research' })).toBeFocused();
  await page.keyboard.press('Enter'); await expect(page.locator('main')).toBeFocused();
  await audit('desktop Explore');
  await page.getByRole('combobox', { name: 'Search scope', exact: true }).selectOption('radius');
  await page.getByLabel('Full UK postcode', { exact: true }).fill('BN1 1AA');
  await page.getByRole('button', { name: 'Use postcode', exact: true }).click();
  await expect(page.locator('.search-circle')).toHaveAttribute('data-radius', '500');
  await expect(page.getByText(/Part of this circle is outside/)).toBeVisible();
  await page.locator('.venue-row').first().focus(); await page.keyboard.press('Enter');
  await expect(page.locator('.selected-venue h4')).toHaveText('Journey Cafe');
  await expect(page.locator('.selected-venue').getByRole('region', { name: 'Field decisions' })).toHaveCount(0);
  await expect(page.locator('.map-access').getByRole('link', { name: 'OpenStreetMap contributors' })).toBeVisible();
  await audit('desktop radius and detail');
  await page.getByRole('link', { name: 'Companies', exact: true }).click();
  await page.locator('.company-row').first().click();
  await expect(page.locator('.selected-company')).toContainText('00000001');
  await audit('desktop Companies');
  await page.getByRole('link', { name: 'Compare', exact: true }).click();
  await page.getByRole('combobox', { name: 'First neighbourhood', exact: true }).selectOption(areaCodes[0]);
  await page.getByRole('combobox', { name: 'Second neighbourhood', exact: true }).selectOption(areaCodes[1]);
  await expect(page.locator('.comparison-cards .area-card')).toHaveCount(2);
  await expect(page.locator('.comparison-cards .area-card').nth(1)).toContainText('Unavailable');
  await audit('desktop Compare');
  await page.getByRole('link', { name: 'Activity', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No observed changes recorded' })).toBeVisible();
  await audit('desktop Activity');
  await page.getByRole('link', { name: 'Data & methodology' }).click();
  await expect(page.getByText('Some source data is older than expected', { exact: true })).toBeVisible();
  await expect(page.getByRole('table', { name: 'Source collection, edition and health' })).toContainText('01/10/2026');
  await expect(page.getByText('current canonical roster', { exact: true })).toHaveCount(0);
  await expect(page.getByText('primary spatial venues', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Hospitality match review — excluded businesses omitted', { exact: true })).toHaveCount(0);
  await page.getByText('eligible resolved supported venues', { exact: true }).click();
  const coverage = page.getByRole('table', { name: 'Location quality', exact: true });
  await expect(coverage).toContainText('50.0%');
  await expect(coverage.getByRole('columnheader', { name: 'Denominator' })).toHaveCount(0);
  await expect(page.getByRole('table', { name: 'Category detail', exact: true })).toContainText('Unavailable');
  await expect(page.getByRole('heading', { name: 'Source attribution' })).toBeVisible();
  await audit('desktop Methodology');
  await page.screenshot({ path: testInfo.outputPath('methodology-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  for (const section of ['Explore', 'Companies', 'Compare', 'Activity', 'Data & methodology']) {
    await page.getByRole('link', { name: section, exact: true }).click();
    await expect(page.locator('main > .page-heading h2')).toBeFocused();
    await expect(page.locator('.feedback.loading')).toHaveCount(0);
    await audit(`mobile ${section}`);
  }
  await page.screenshot({ path: testInfo.outputPath('methodology-mobile.png'), fullPage: true });
  await page.getByRole('link', { name: 'Data reuse and downloadable-data status' }).click();
  await expect(page.getByRole('heading', { name: 'Data reuse', exact: true })).toBeVisible();
  await expect(page.getByText(/no UrbanLens data bundle is published yet/)).toBeVisible();
  await audit('reuse page');
  expect(requests.filter(url => !url.pathname.endsWith('/meta')).every(url => url.searchParams.get('release_id') === firstRelease)).toBeTruthy();
  expect(errors).toEqual([]);
  await testInfo.attach('accessibility-report', { body: JSON.stringify(reports, null, 2), contentType: 'application/json' });
});

test('slow startup, outage, throttling, cutoff, timeout and expiry retain a clear manual recovery path', async ({ page }) => {
  test.setTimeout(60_000);
  await page.clock.install();
  const control: JourneyControl = { release: firstRelease, mode: 'slow' }, requests: URL[] = [];
  await journeyApi(page, control, requests);
  await page.goto('/');
  await expect(page.getByText('Loading this view…', { exact: true })).toBeVisible();
  await expect(page.locator('.competition-total strong')).toHaveText('1');
  control.mode = 'outage';
  await page.getByLabel('Bakeries', { exact: true }).uncheck();
  await expect(page.getByRole('heading', { name: 'Data is temporarily unavailable' })).toBeVisible();
  await expect(page.locator('.competition-summary')).toHaveCount(0);
  control.mode = 'throttle';
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Service is busy' })).toBeVisible();
  control.mode = 'limit';
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Service temporarily limited' })).toBeVisible();
  const attempts = requests.length;
  await page.clock.fastForward(60_000);
  expect(requests.length).toBe(attempts);
  control.mode = 'timeout';
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.getByText('Loading this view…', { exact: true })).toBeVisible();
  await page.clock.fastForward(16_000);
  await expect(page.getByRole('heading', { name: 'Request timed out' })).toBeVisible();
  control.mode = 'ready';
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.locator('.competition-total strong')).toHaveText('1');
  control.mode = 'expired';
  await page.getByLabel('Restaurants', { exact: true }).uncheck();
  await expect(page.getByRole('heading', { name: 'This data version has expired' })).toBeVisible();
  control.release = secondRelease; control.mode = 'ready';
  await page.getByRole('button', { name: 'Continue with current data', exact: true }).click();
  await expect(page.locator('.competition-total strong')).toHaveText('1');
  await expect(page.getByLabel('Bakeries', { exact: true })).not.toBeChecked();
  await expect(page.getByLabel('Restaurants', { exact: true })).not.toBeChecked();
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No matching venues', exact: true })).toBeVisible();
  await expect(page.locator('.competition-total strong')).toHaveText('0');
});
